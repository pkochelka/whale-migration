"""Generate docs/SOURCES.md (licenses + citations) and docs/DATA_SUMMARY.md (record counts)."""
from __future__ import annotations

import json
from datetime import date

import pandas as pd

from ..report import load_reports, reports_markdown


SOURCE_INFO = {
    "whalinghistory": ("WhalingHistory.org — American Offshore Whaling Logbook Data (AOWL)",
                       "https://whalinghistory.org/participate/download/"),
    "obis": ("OBIS — Ocean Biodiversity Information System (via pyobis)", "https://api.obis.org/v3"),
    "gbif": ("GBIF — Global Biodiversity Information Facility (via pygbif)", "https://api.gbif.org/v1"),
    "seamap": ("OBIS-SEAMAP / Happywhale photo-ID (Duke IPT DwC-A)", "https://ipt.env.duke.edu"),
    "movebank": ("Movebank public tracking studies", "https://www.movebank.org"),
}
ENV_INFO = {
    "sst": "Sea surface temperature (HadISST via NOAA ERDDAP)",
    "chlorophyll": "Chlorophyll-a (ESA OC-CCI via NOAA ERDDAP)",
    "sea_ice": "Sea ice concentration & extent (NSIDC G02202 v6, G02135)",
    "mpa": "Marine protected areas (Protected Planet WDPA / WD-OECM)",
    "shipping": "Global shipping traffic density (IMF / World Bank)",
}


def _md_table(df: pd.DataFrame) -> str:
    cols = [str(c) for c in df.columns]
    lines = ["| " + " | ".join(cols) + " |", "|" + "|".join("---:" if pd.api.types.is_numeric_dtype(df[c])
                                                           else "---" for c in df.columns) + "|"]
    for _, r in df.iterrows():
        lines.append("| " + " | ".join(f"{v:,}" if isinstance(v, (int,)) and not isinstance(v, bool)
                                       else str(v) for v in r.values) + " |")
    return "\n".join(lines)


def write_sources(cfg) -> None:
    occ_p = cfg.processed / "occurrences.parquet"
    lines = [f"# Data sources, licenses and citations", "",
             f"_Generated by `python -m pipeline docs` on {date.today().isoformat()}. Every record in "
             "`data/processed/occurrences.parquet` also carries its own `license` and `citation`._", "",
             "## Occurrence sources", ""]
    occ = pd.read_parquet(occ_p, columns=["source", "dataset_id", "license", "citation"]) if occ_p.exists() else None
    for s, (title, url) in SOURCE_INFO.items():
        lines += [f"### {title}", "", f"- Endpoint: {url}"]
        stub = cfg.raw / s / "STUB.json"
        if stub.exists():
            lines += [f"- **Status: not fetched** — {json.loads(stub.read_text())['reason']}", ""]
            continue
        sc = cfg.source(s)
        if sc.get("license"):
            lines.append(f"- License: {sc['license']}")
        if sc.get("citation"):
            lines.append(f"- Citation: {' '.join(sc['citation'].split())}")
        if occ is not None and (occ["source"] == s).any():
            sub = occ[occ["source"] == s]
            lic = sub["license"].value_counts()
            lines.append(f"- Records after cleaning/dedup: {len(sub):,} from {sub['dataset_id'].nunique():,} datasets")
            lines.append("- Record licenses: " + ", ".join(f"{k} ({v:,})" for k, v in lic.head(8).items())
                         + (f", … {len(lic) - 8} more" if len(lic) > 8 else ""))
            top = sub.groupby(["dataset_id", "citation"]).size().sort_values(ascending=False).head(15)
            lines += ["", "<details><summary>Top datasets by record count</summary>", ""]
            for (ds, cit), n in top.items():
                lines.append(f"- `{ds}` ({n:,}): {cit[:400]}")
            lines += ["", "</details>"]
        lines.append("")
    lines += ["## Environmental layers", ""]
    for s, title in ENV_INFO.items():
        sc = cfg.source(s)
        lines += [f"### {title}", "", f"- License: {sc.get('license', 'see provider')}",
                  f"- Citation: {' '.join(str(sc.get('citation', '')).split())}", ""]
    lines += ["## Supporting data", "",
              "- Natural Earth 1:10m land polygons (public domain) — land mask and distance to coast.",
              "- WoRMS (World Register of Marine Species) — taxonomic names and AphiaIDs, via pyworms. "
              "WoRMS Editorial Board (2026). https://www.marinespecies.org. doi:10.14284/170", "",
              "## License caveats", "",
              "- **WDPA**: non-commercial use only and *no redistribution*; derived files stay local.",
              "- **HadISST**: Crown copyright, academic research use only.",
              "- **CC BY-NC** records (most Happywhale/OBIS-SEAMAP data) are non-commercial.",
              "- Records flagged `license_all_rights_reserved` (\"No use without permission\") need the "
              "rights holder's permission before publication; set `licenses.drop_all_rights_reserved: true` "
              "to exclude them.", ""]
    (cfg.root / "docs").mkdir(exist_ok=True)
    (cfg.root / "docs" / "SOURCES.md").write_text("\n".join(lines), encoding="utf-8")


def summary_markdown(cfg) -> str:
    out = cfg.processed
    parts = ["# Data summary", "", f"_Generated {date.today().isoformat()} by `python -m pipeline docs`._", ""]
    tot = out / "summary_totals.json"
    if tot.exists():
        t = json.loads(tot.read_text())
        parts += [f"**{t['records_out']:,} unified occurrence records** "
                  f"({t['records_in']:,} cleaned records in, {t['duplicates_removed']:,} cross-source "
                  f"duplicates removed: {t['exact_duplicates']:,} exact-ID, {t['fuzzy_duplicates']:,} fuzzy).", ""]
    p = out / "summary_source_species_decade.csv"
    if p.exists():
        s = pd.read_csv(p)
        sp = s.pivot_table(index="species_scientific", columns="source", values="records", aggfunc="sum",
                           fill_value=0)
        sp["total"] = sp.sum(axis=1)
        parts += ["### Records per species and source", "", _md_table(sp.reset_index().astype(
            {c: int for c in sp.columns})), ""]
        s["era"] = pd.cut(s["decade"], [0, 1919, 1979, 1999, 2009, 2019, 2100],
                          labels=["≤1910s", "1920–1970s", "1980–90s", "2000s", "2010s", "2020s"])
        dec = s.pivot_table(index="species_scientific", columns="era", values="records", aggfunc="sum",
                            fill_value=0, observed=False)
        parts += ["### Records per species and era", "", _md_table(dec.reset_index().astype(
            {c: int for c in dec.columns})), ""]
        d2 = s.pivot_table(index="decade", columns="source", values="records", aggfunc="sum", fill_value=0)
        d2["total"] = d2.sum(axis=1)
        parts += ["<details><summary>Records per decade and source</summary>", "",
                  _md_table(d2.reset_index().astype(int)), "", "</details>", ""]
    reps = load_reports(cfg.interim / "reports")
    if reps:
        parts += ["### Cleaning report (per source)", "", reports_markdown(reps), "",
                  "Full reports: `data/interim/reports/<source>.json`.", ""]
    return "\n".join(parts)


def write_summary(cfg) -> None:
    (cfg.root / "docs").mkdir(exist_ok=True)
    (cfg.root / "docs" / "DATA_SUMMARY.md").write_text(summary_markdown(cfg), encoding="utf-8")


def write_all(cfg) -> None:
    write_sources(cfg)
    write_summary(cfg)
